double clamp(double value, double min, double max) {
	return std::min(std::max(value, min), max);
}

double magnitude(const Vector2& value) {
	return std::hypot(value.x, value.y);
}

Vector2 add(const Vector2& left, const Vector2& right) {
	return {left.x + right.x, left.y + right.y};
}

NormalizedVertex to_ndc_point(double x, double y, const Scenario& scenario) {
	const auto& bounds = scenario.view_bounds;
	const double normalized_x =
		((x - bounds.min_x) / std::max(bounds.max_x - bounds.min_x, 1e-6)) * 2.0 - 1.0;
	const double normalized_y =
		((y - bounds.min_y) / std::max(bounds.max_y - bounds.min_y, 1e-6)) * 2.0 - 1.0;

	return {
		static_cast<float>(clamp(normalized_x, -0.96, 0.96)),
		static_cast<float>(clamp(normalized_y, -0.96, 0.96)),
	};
}

Vector2 build_electrostatic_field(double charge, const Vector2& source, const Vector2& target) {
	const double dx = target.x - source.x;
	const double dy = target.y - source.y;
	const double distance_squared = std::max(dx * dx + dy * dy, 0.2);
	const double distance = std::sqrt(distance_squared);
	const double scale_factor = (6.0 * charge) / (distance_squared * distance);
	return {dx * scale_factor, dy * scale_factor};
}

Snapshot build_point_charge_snapshot(const Scenario& scenario) {
	const Vector2 probe_point = scenario.probe_point.value_or(scenario.initial_position);
	const double first_charge = scenario.charge_magnitude.value_or(1.0);
	const double second_charge = scenario.secondary_charge_magnitude.value_or(-1.0);
	const Vector2 first_source = scenario.source_point.value_or(Vector2{-2.0, 0.0});
	const Vector2 second_source = scenario.secondary_source_point.value_or(Vector2{2.0, 0.0});
	const Vector2 first_field = build_electrostatic_field(first_charge, first_source, probe_point);
	const Vector2 second_field = build_electrostatic_field(second_charge, second_source, probe_point);
	const Vector2 electric_field = add(first_field, second_field);
	const double potential =
		6.0 * first_charge / std::max(std::hypot(probe_point.x - first_source.x, probe_point.y - first_source.y), 0.4) +
		6.0 * second_charge / std::max(std::hypot(probe_point.x - second_source.x, probe_point.y - second_source.y), 0.4);

	return {
		0.0,
		probe_point,
		electric_field,
		{0.0, 0.0},
		electric_field,
		potential,
		magnitude(electric_field),
		magnitude(electric_field),
		potential,
		true,
	};
}

Snapshot build_moving_charge_snapshot(const Scenario& scenario, double time_seconds) {
	const double charge = scenario.charge_magnitude.value_or(1.0);
	const double mass = std::max(scenario.mass.value_or(1.0), 0.1);
	const double magnetic_field_strength = scenario.magnetic_field_strength.value_or(1.0);
	const Vector2 initial_velocity = scenario.initial_velocity.value_or(Vector2{2.4, 1.2});
	const double omega = (charge * magnetic_field_strength) / mass;
	Vector2 position = scenario.initial_position;
	Vector2 velocity = initial_velocity;

	if (std::abs(omega) > 1e-6) {
		const double cos_theta = std::cos(omega * time_seconds);
		const double sin_theta = std::sin(omega * time_seconds);
		velocity = {
			initial_velocity.x * cos_theta + initial_velocity.y * sin_theta,
			initial_velocity.y * cos_theta - initial_velocity.x * sin_theta,
		};
		position = {
			scenario.initial_position.x +
				(initial_velocity.x * sin_theta + initial_velocity.y * (1.0 - cos_theta)) / omega,
			scenario.initial_position.y +
				(initial_velocity.y * sin_theta - initial_velocity.x * (1.0 - cos_theta)) / omega,
		};
	} else {
		position = {
			scenario.initial_position.x + initial_velocity.x * time_seconds,
			scenario.initial_position.y + initial_velocity.y * time_seconds,
		};
	}

	const Vector2 magnetic_field{0.0, magnetic_field_strength};
	const Vector2 force{
		charge * velocity.y * magnetic_field_strength,
		-charge * velocity.x * magnetic_field_strength,
	};

	return {
		time_seconds,
		position,
		{0.0, 0.0},
		magnetic_field,
		force,
		0.0,
		std::abs(magnetic_field_strength),
		magnitude(force),
		0.5 * mass * magnitude(velocity) * magnitude(velocity),
		false,
	};
}

Snapshot build_current_loop_snapshot(const Scenario& scenario) {
	const Vector2 probe_point = scenario.probe_point.value_or(Vector2{0.0, 2.0});
	const double current = scenario.current.value_or(0.0);
	const double loop_radius = std::max(scenario.loop_radius.value_or(1.0), 0.1);
	const double radial_distance = std::hypot(probe_point.x, probe_point.y);
	const double magnetic_field_strength =
		(1.25663706 * current * loop_radius * loop_radius) /
		(2.0 * std::pow(loop_radius * loop_radius + radial_distance * radial_distance, 1.5));

	return {
		0.0,
		probe_point,
		{0.0, 0.0},
		{0.0, magnetic_field_strength},
		{0.0, 0.0},
		0.0,
		std::abs(magnetic_field_strength),
		0.0,
		0.5 * current * current * loop_radius,
		true,
	};
}

Snapshot build_capacitor_snapshot(const Scenario& scenario) {
	const Vector2 probe_point = scenario.probe_point.value_or(scenario.initial_position);
	const double separation = std::max(scenario.plate_separation.value_or(1.0), 0.1);
	const double voltage = scenario.potential_difference.value_or(0.0);
	const double half_gap = separation / 2.0;
	const double clamped_probe_x = clamp(probe_point.x, -half_gap, half_gap);
	const Vector2 electric_field{voltage / separation, 0.0};
	const double potential = ((half_gap - clamped_probe_x) / separation) * voltage;
	const Vector2 position{
		clamped_probe_x,
		clamp(probe_point.y, scenario.view_bounds.min_y, scenario.view_bounds.max_y),
	};

	return {
		0.0,
		position,
		electric_field,
		{0.0, 0.0},
		electric_field,
		potential,
		magnitude(electric_field),
		magnitude(electric_field),
		0.5 * voltage * voltage,
		true,
	};
}

Snapshot build_induction_snapshot(const Scenario& scenario, double time_seconds) {
	const double flux_rate = scenario.flux_rate.value_or(0.0);
	const double inductance = scenario.inductance.value_or(1.0);
	const double duration_seconds = std::max(scenario.duration_seconds, 1.0);
	const double phase = (time_seconds / duration_seconds) * kPi * 2.0;
	const double magnetic_flux = flux_rate * std::sin(phase);
	const double induced_emf = -inductance * flux_rate * std::cos(phase);

	return {
		time_seconds,
		scenario.probe_point.value_or(scenario.initial_position),
		{induced_emf, 0.0},
		{0.0, magnetic_flux},
		{induced_emf, 0.0},
		induced_emf,
		std::abs(magnetic_flux),
		std::abs(induced_emf),
		0.5 * inductance * flux_rate * flux_rate,
		true,
	};
}

void append_rectangle(
	std::vector<NormalizedVertex>& vertices,
	double x,
	double y,
	double width,
	double height,
	const Scenario& scenario) {
	vertices.push_back(to_ndc_point(x, y, scenario));
	vertices.push_back(to_ndc_point(x + width, y, scenario));
	vertices.push_back(to_ndc_point(x + width, y, scenario));
	vertices.push_back(to_ndc_point(x + width, y + height, scenario));
	vertices.push_back(to_ndc_point(x + width, y + height, scenario));
	vertices.push_back(to_ndc_point(x, y + height, scenario));
	vertices.push_back(to_ndc_point(x, y + height, scenario));
	vertices.push_back(to_ndc_point(x, y, scenario));
}

