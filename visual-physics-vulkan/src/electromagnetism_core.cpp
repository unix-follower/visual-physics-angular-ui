std::string_view to_string(ScenarioId id) {
	switch (id) {
	case ScenarioId::PointChargeElectrostatics:
		return "point-charge-electrostatics";
	case ScenarioId::MovingChargeMagneticField:
		return "moving-charge-magnetic-field";
	case ScenarioId::CurrentLoopMagneticField:
		return "current-loop-magnetic-field";
	case ScenarioId::CapacitorPotentialField:
		return "capacitor-potential-field";
	case ScenarioId::ElectromagneticInduction:
		return "electromagnetic-induction";
	}

	throw std::runtime_error("Unknown electromagnetism scenario id");
}

std::optional<ScenarioId> parse_scenario_id(std::string_view value) {
	if (value == "point-charge-electrostatics") {
		return ScenarioId::PointChargeElectrostatics;
	}
	if (value == "moving-charge-magnetic-field") {
		return ScenarioId::MovingChargeMagneticField;
	}
	if (value == "current-loop-magnetic-field") {
		return ScenarioId::CurrentLoopMagneticField;
	}
	if (value == "capacitor-potential-field") {
		return ScenarioId::CapacitorPotentialField;
	}
	if (value == "electromagnetic-induction") {
		return ScenarioId::ElectromagneticInduction;
	}
	return std::nullopt;
}

Scenario make_default_scenario(ScenarioId id) {
	const auto match = std::find_if(
		kDefaultScenarios.begin(),
		kDefaultScenarios.end(),
		[id](const Scenario& scenario) { return scenario.id == id; });
	if (match == kDefaultScenarios.end()) {
		throw std::runtime_error("Unsupported electromagnetism scenario id");
	}
	return *match;
}

Snapshot sample_scenario(const Scenario& scenario, double time_seconds) {
	switch (scenario.id) {
	case ScenarioId::PointChargeElectrostatics:
		return build_point_charge_snapshot(scenario);
	case ScenarioId::MovingChargeMagneticField:
		return build_moving_charge_snapshot(scenario, time_seconds);
	case ScenarioId::CurrentLoopMagneticField:
		return build_current_loop_snapshot(scenario);
	case ScenarioId::CapacitorPotentialField:
		return build_capacitor_snapshot(scenario);
	case ScenarioId::ElectromagneticInduction:
		return build_induction_snapshot(scenario, time_seconds);
	}

	throw std::runtime_error("Unsupported electromagnetism scenario id");
}

std::vector<Sample> build_samples(const Scenario& scenario, std::size_t sample_count) {
	const std::size_t resolved_sample_count = std::max<std::size_t>(sample_count, 2);
	std::vector<Sample> samples;
	samples.reserve(resolved_sample_count);
	for (std::size_t index = 0; index < resolved_sample_count; index += 1) {
		const double time_seconds =
			(scenario.id == ScenarioId::MovingChargeMagneticField ||
			 scenario.id == ScenarioId::ElectromagneticInduction)
				? (static_cast<double>(index) / static_cast<double>(resolved_sample_count - 1)) *
					scenario.duration_seconds
				: 0.0;
		const Snapshot snapshot = sample_scenario(scenario, time_seconds);
		samples.push_back({
			time_seconds,
			snapshot.position.x,
			snapshot.position.y,
			snapshot.field_magnitude,
			snapshot.force_magnitude,
			snapshot.potential,
		});
	}
	return samples;
}

std::vector<NormalizedVertex> build_axes_vertices(const Scenario& scenario) {
	return {
		to_ndc_point(scenario.view_bounds.min_x, 0.0, scenario),
		to_ndc_point(scenario.view_bounds.max_x, 0.0, scenario),
		to_ndc_point(0.0, scenario.view_bounds.min_y, scenario),
		to_ndc_point(0.0, scenario.view_bounds.max_y, scenario),
	};
}

std::vector<NormalizedVertex> build_marker_vertices(
	const Snapshot& snapshot,
	const Scenario& scenario,
	float aspect_ratio) {
	const auto center = to_ndc_point(snapshot.position.x, snapshot.position.y, scenario);
	const float half_width = 0.022F;
	const float safe_aspect = std::max(aspect_ratio, 0.001F);
	const float half_height = aspect_ratio >= 1.0F ? half_width * aspect_ratio : half_width / safe_aspect;

	return {
		{center.x - half_width, center.y - half_height},
		{center.x + half_width, center.y - half_height},
		{center.x - half_width, center.y + half_height},
		{center.x - half_width, center.y + half_height},
		{center.x + half_width, center.y - half_height},
		{center.x + half_width, center.y + half_height},
	};
}

std::vector<NormalizedVertex> build_scenario_vertices(
	const Snapshot& snapshot,
	const Scenario& scenario) {
	std::vector<NormalizedVertex> vertices;
	auto append_line = [&](const Vector2& start, const Vector2& end) {
		vertices.push_back(to_ndc_point(start.x, start.y, scenario));
		vertices.push_back(to_ndc_point(end.x, end.y, scenario));
	};

	if (scenario.id == ScenarioId::PointChargeElectrostatics) {
		append_line(scenario.source_point.value_or(Vector2{-2.0, 0.0}), snapshot.position);
		append_line(scenario.secondary_source_point.value_or(Vector2{2.0, 0.0}), snapshot.position);
		return vertices;
	}

	if (scenario.id == ScenarioId::MovingChargeMagneticField) {
		append_rectangle(vertices, -2.8, -2.8, 5.6, 5.6, scenario);
		return vertices;
	}

	if (scenario.id == ScenarioId::CurrentLoopMagneticField) {
		const double radius = scenario.loop_radius.value_or(1.8);
		for (int index = 0; index < 32; index += 1) {
			const double start_angle = (static_cast<double>(index) / 32.0) * kPi * 2.0;
			const double end_angle = (static_cast<double>(index + 1) / 32.0) * kPi * 2.0;
			append_line(
				{std::cos(start_angle) * radius, std::sin(start_angle) * radius},
				{std::cos(end_angle) * radius, std::sin(end_angle) * radius});
		}
		return vertices;
	}

	if (scenario.id == ScenarioId::CapacitorPotentialField) {
		const double half_gap = std::max(scenario.plate_separation.value_or(2.0) / 2.0, 0.4);
		append_line({-half_gap, -2.5}, {-half_gap, 2.5});
		append_line({half_gap, -2.5}, {half_gap, 2.5});
		return vertices;
	}

	append_rectangle(vertices, -1.8, -1.8, 3.6, 3.6, scenario);
	append_rectangle(vertices, -1.1, -1.1, 2.2, 2.2, scenario);
	return vertices;
}

